#!/usr/bin/env node
/*
 * Writes the files made from the token list (tokens/theme-tokens.json, a copy of a neo-web release's):
 *
 *   generated/builder-tokens.js   the list for the builder's own page (names, dark defaults, fallbacks, kinds, parts)
 *   sync/v1/theme-sync.js         theme-sync (sync/theme-sync.src.js) with the dark defaults written in
 *
 * The package is installed as its repository is at the release tag, so both are committed.
 *
 *   node scripts/build.js            write them
 *   node scripts/build.js --check    fail when a committed file is not what the token list makes
 *
 * Not an npm script: package.json is the package's manifest, and its `scripts` are what the App Store runs.
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const TOKENS = path.join(ROOT, 'tokens', 'theme-tokens.json');
const SOURCE = path.join(ROOT, 'tokens', 'SOURCE');
const SYNC_SRC = path.join(ROOT, 'sync', 'theme-sync.src.js');
const OUT_BUILDER = path.join(ROOT, 'generated', 'builder-tokens.js');
const OUT_SYNC = path.join(ROOT, 'sync', 'v1', 'theme-sync.js');

function readTokens() {
    const list = JSON.parse(fs.readFileSync(TOKENS, 'utf8'));
    if (!Array.isArray(list) || !list.length) throw new Error('tokens/theme-tokens.json: not a token list');
    const names = new Set();
    for (const t of list) {
        if (!t || typeof t.name !== 'string' || typeof t.dark !== 'string') throw new Error(`tokens/theme-tokens.json: bad entry ${JSON.stringify(t)}`);
        if (t.fallback !== undefined && !names.has(t.fallback)) throw new Error(`tokens/theme-tokens.json: ${t.name} falls back to ${t.fallback}, which is not declared before it`);
        names.add(t.name);
    }
    return list;
}

function generate() {
    const tokens = readTokens();
    const source = fs.readFileSync(SOURCE, 'utf8').trim();
    const header = '/* Generated by scripts/build.js from tokens/theme-tokens.json (' + source + '). Do not edit. */\n';

    const builder =
        header +
        '(function (root, data) {\n' +
        "    if (typeof module === 'object' && module.exports) module.exports = data;\n" +
        '    else root.NeoThemeTokens = data;\n' +
        '})(this, ' +
        JSON.stringify({ source, tokens }, null, 1) +
        ');\n';

    const dark = {};
    for (const t of tokens) dark[t.name] = t.dark;
    const src = fs.readFileSync(SYNC_SRC, 'utf8');
    const MARK = '/* @dark */ {}';
    if (src.split(MARK).length !== 2) throw new Error('sync/theme-sync.src.js: expected one ' + MARK);
    const sync = header + src.replace(MARK, JSON.stringify(dark));
    // served by a cgi script whose Content-Length is the text's length: one byte per character
    const wide = sync.search(/[^\x00-\x7f]/);
    if (wide >= 0) throw new Error(`sync/v1/theme-sync.js: non-ASCII character at ${wide}: keep sync/theme-sync.src.js ASCII`);

    return { [OUT_BUILDER]: builder, [OUT_SYNC]: sync };
}

function main() {
    const check = process.argv.includes('--check');
    const files = generate();
    const stale = [];
    for (const [file, text] of Object.entries(files)) {
        const rel = path.relative(ROOT, file);
        if (check) {
            if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) stale.push(rel);
        } else {
            fs.mkdirSync(path.dirname(file), { recursive: true });
            fs.writeFileSync(file, text);
            console.log('wrote ' + rel);
        }
    }
    if (stale.length) {
        console.error('out of date (run node scripts/build.js): ' + stale.join(', '));
        process.exit(1);
    }
}

module.exports = { generate, readTokens, ROOT };
if (require.main === module) main();
